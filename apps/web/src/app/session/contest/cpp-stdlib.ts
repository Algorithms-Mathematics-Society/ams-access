/**
 * The C++ standard library surface offered by the editor's completions.
 *
 * This replaces a hand-written list of 38 names. Thirty-eight is enough to
 * look like autocomplete and not enough to be it: typing `std::era` — reaching
 * for `erase` — offered `unordered_map`, `next_permutation` and
 * `prev_permutation`, because `erase` was not in the list and those three were
 * the closest fuzzy matches. A candidate cannot tell "this name does not
 * exist" from "this name is not in our list", so a short list is worse than
 * none: it teaches them to distrust the editor mid-exam.
 *
 * The contest compiles as C++23, so the completions go up to C++23 —
 * `<ranges>`, `<bit>`, `<format>`, `<print>`, `<expected>`, `<flat_map>` and
 * the rest are all things a candidate may legitimately reach for and, until
 * now, would have been silently told did not exist.
 *
 * This is a curated index, not a compiler frontend: it is a flat name list
 * with the owning header, so it cannot know that `.erase` on a `vector` and
 * on a `map` differ, and it will happily offer a name in a scope where it does
 * not apply. That is the accepted trade — a real index means shipping clangd,
 * and the failure mode here is an extra suggestion rather than a missing one.
 *
 * `detail` carries the header, because in a closed exam room "which header do
 * I include" is the question a candidate cannot look up.
 */

