/**
 * One entry per name. A name owned by more than one header (`get`, `swap`,
 * `find`, `max`) keeps the first group that claims it, so the list has no
 * duplicates — CodeMirror renders duplicates as separate rows, and two
 * identical labels in a completion popup is worse than one imprecise header.
 */
export const cppStdlibCompletions: Completion[] = (() => {
  const seen = new Set<string>();
  const out: Completion[] = [];
  for (const group of GROUPS) {
    for (const label of group.names) {
      if (seen.has(label)) continue;
      seen.add(label);
      out.push({ label, type: group.type, detail: group.header });
    }
  }
  return out;
})();
